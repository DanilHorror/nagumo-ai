package ru.nagumo.verity.client.hud;

/**
 * Визуальные состояния HUD-виджета компаньона (раздел 7 ТЗ). Пока переключаются
 * только тестовой командой ({@link CompanionHudTestCommand}) — реальные переходы
 * (после срабатывания имени, во время инференса, во время TTS-ответа) появятся
 * вместе с голосовым пайплайном и brain на клиенте (раздел 11 ТЗ, шаги 3+).
 */
public enum CompanionHudState {
    /** Покой/ожидание — компаньон не занят. */
    IDLE,
    /** Сработало имя — идёт полная транскрипция обращения. */
    LISTENING,
    /** Идёт инференс LLM. */
    THINKING,
    /** Идёт TTS-ответ. */
    SPEAKING
}
