package ru.nagumo.verity.client.brain;

/**
 * Уровень локальной LLM-модели компаньона (раздел 6 ТЗ). {@code OFF} — явный
 * переключатель "без компаньона", полностью пропускает инициализацию инференса.
 *
 * Сам enum не привязан к конкретным файлам/движку — привязка к реальным тегам
 * Ollama-моделей (раздел 11 ТЗ, шаг 5) живёт в {@link ModelManager#ollamaModelFor}.
 */
public enum ModelTier {
    /** Без компаньона — инференс не инициализируется вообще. */
    OFF,
    /** ~1-2B параметров — для слабых/встроенных GPU. */
    MINI,
    /** ~3-4B параметров — дефолт для большинства игровых видеокарт (6-8 ГБ VRAM). */
    LITE,
    /** ~7-8B параметров — для более мощного железа (10-12 ГБ VRAM и выше). */
    STANDARD
}
